export function classifyAsCore(blockName: string, generalCat: string, cp: number, name: string): string | undefined {
	if (blockName === 'Greek and Coptic' || blockName === 'Greek Extended') return 'greek';
	const isLatinBlock = blockName.startsWith('Latin') || ['Basic Latin', 'IPA Extensions', 'Phonetic Extensions', 'Phonetic Extensions Supplement'].includes(blockName);

	// Mathematical alphanumeric symbols
	if (blockName === 'Mathematical Alphanumeric Symbols' || scatteredMathematicalAlphanumericSymbols.some((s) => s.cp === cp)) {
		return 'math_alphanumerics';
	}
	// Letters
	if (generalCat === 'Lu' || generalCat === 'Ll' || generalCat === 'Lt' || generalCat === 'Lo') {
		if (isLatinBlock) {
			return 'latin';
		}
	}
	// Modifier letters (e.g. ʰ, ʼ) vs standalone diacritics (e.g. ¨, ˇ, ˘)
	if (generalCat === 'Lm' || generalCat === 'Sk') {
		return name.startsWith('MODIFIER LETTER ') ? 'modifier' : 'dia';
	}
	// Combining marks
	if ((['Mn', 'Mc', 'Me'].includes(generalCat)) && blockName.startsWith('Combining')) {
		return 'combining';
	}
	// Numbers
	if (['Nd', 'Nl', 'No'].includes(generalCat)) {
		return 'math_number';
	}
	// Punctuation
	if (generalCat.startsWith('P') || generalCat.startsWith('Z')) {
		return 'punctuation';
	}
	// Format
	if (generalCat === 'Cf' || generalCat === 'Cc' || blockName === 'Variation Selectors') {
		return 'format';
	}
	// Math operators
	if (generalCat === 'Sm') return 'math_operators';
	// Currency
	if (generalCat === 'Sc' && (isLatinBlock || blockName === 'Currency Symbols' || scatteredCurrencySymbols.includes(cp))) {
		return 'currency';
	}
	// Emoji
	if (generalCat === 'So' && emojiPresentationRanges.some((range) => cp >= range[0] && cp <= range[1])) {
		return 'emoji';
	}
	// Symbols other
	if (generalCat === 'So' || symbolBlockRanges.some((range) => cp >= range.start && cp <= range.end)) {
		return 'misc';
	}

	return undefined;
}

export default function classify(blockName: string, generalCat: string, cp: number, name: string): string | undefined {
	if (!CORE_BLOCKS.has(blockName)) {
		return blockToGroup(blockName);
	}
	return classifyAsCore(blockName, generalCat, cp, name) ?? blockName.toLowerCase().replace(/\s+/g, '_').replace(/[^a-z0-9_]/g, '');
}
